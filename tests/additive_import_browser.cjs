"use strict";
const assert=require("node:assert/strict"), fs=require("node:fs/promises"), os=require("node:os"), path=require("node:path");
const {execFileSync}=require("node:child_process"), {pathToFileURL}=require("node:url");
const {launch,offlineContext}=require("./browser_support.cjs");
(async()=>{
 const directory=await fs.mkdtemp(path.join(os.tmpdir(),"afterlife-add-import-")), root=path.resolve(__dirname,".."), browser=await launch();
 try {
  const artifact=path.join(directory,"app.html"), backup=path.join(directory,"backup.json");
  execFileSync(process.env.PYTHON||"python3",["-m","afterlife","examples/task-tracker/app.json","examples/task-tracker/records.json","-o",artifact],{cwd:root});
  const original=await fs.readFile(artifact), context=await offlineContext(browser,{acceptDownloads:true}), errors=[],network=[];
  const open=async()=>{const p=await context.newPage();p.on("pageerror",e=>errors.push(e.message));p.on("request",r=>{if(/^https?:/.test(r.url()))network.push(r.url());});await p.goto(pathToFileURL(artifact).href);return p;};
  const page=await open(), payload=await page.evaluate(()=>JSON.parse(document.querySelector("#afterlife-data").textContent));
  const initial=payload.records, fresh={...initial[0],id:"new-record",title:"Imported distinct task"};
  const incoming={format:"afterlife-data/v1",app_id:payload.spec.app_id,spec_fingerprint:payload.spec_fingerprint,records:[initial[0],fresh]};
  const stored=()=>page.evaluate(key=>localStorage.getItem(key),payload.storage_key);
  await fs.writeFile(backup,JSON.stringify(incoming));
  await page.locator("#import-file").setInputFiles(backup);
  await page.getByRole("button",{name:"Add new records",exact:true}).waitFor();
  assert.match(await page.getByRole("region",{name:"Import review"}).textContent(),/Add mode keeps all current records/);
  await page.getByRole("button",{name:"Cancel import",exact:true}).click();assert.equal(await stored(),null);
  await page.locator(`tr[data-record-id="${initial[0].id}"]`).getByRole("button",{name:"Edit",exact:true}).click();
  await page.locator("#field-title").fill("Unsaved draft");
  await page.locator("#import-file").setInputFiles(backup);
  page.once("dialog",d=>d.dismiss());await page.getByRole("button",{name:"Add new records",exact:true}).click();
  assert.equal(await stored(),null);assert.equal(await page.locator("#field-title").inputValue(),"Unsaved draft");
  page.once("dialog",d=>d.accept());await page.getByRole("button",{name:"Cancel",exact:true}).click();
  await page.getByRole("button",{name:"Add new records",exact:true}).click();
  await page.locator("#message").filter({hasText:"Added 1 new records"}).waitFor();
  const merged=[...initial,fresh];assert.deepEqual(JSON.parse(await stored()).records,merged);
  await page.reload();assert.deepEqual(JSON.parse(await stored()).records,merged);
  // Same-ID data differences disable additive mode without replacing old data.
  const conflict={...incoming,records:[{...fresh,title:"Conflicting title"},{...fresh,id:"another-new"}]};
  await fs.writeFile(backup,JSON.stringify(conflict));await page.locator("#import-file").setInputFiles(backup);
  assert.equal(await page.getByRole("button",{name:"Add new records",exact:true}).isDisabled(),true);
  assert.deepEqual(JSON.parse(await stored()).records,merged);
  await page.getByRole("button",{name:"Cancel import",exact:true}).click();
  await fs.writeFile(backup,JSON.stringify({...incoming,records:[{...fresh,id:"third-new"}]}));
  await page.locator("#import-file").setInputFiles(backup);
  const writer=await open();await writer.locator("#import-file").setInputFiles(backup);
  await writer.getByRole("button",{name:"Add new records",exact:true}).click();
  await writer.locator("#message").filter({hasText:"Added 1 new records"}).waitFor();
  const winning=await stored();await page.getByRole("button",{name:"Add new records",exact:true}).click();
  assert.equal(await stored(),winning);
  const exported=writer.waitForEvent("download");await writer.getByRole("button",{name:"Export JSON",exact:true}).click();
  const output=path.join(directory,"merged.json");await (await exported).saveAs(output);
  assert.deepEqual(JSON.parse(await fs.readFile(output,"utf8")).records,[...merged,{...fresh,id:"third-new"}]);
  const capData=path.join(directory,"cap-data.json"), capHTML=path.join(directory,"cap.html");
  await fs.writeFile(capData,JSON.stringify({records:Array.from({length:10000},(_,i)=>({...initial[0],id:`cap-${i}`}))}));
  execFileSync(process.env.PYTHON||"python3",["-m","afterlife","examples/task-tracker/app.json",capData,"-o",capHTML],{cwd:root});
  const capped=await context.newPage();await capped.goto(pathToFileURL(capHTML).href);
  await capped.locator("#import-file").setInputFiles(backup);
  await capped.getByRole("button",{name:"Add new records",exact:true}).click();
  await capped.locator("#message").filter({hasText:"at most 10,000 records"}).waitFor();
  const capKey=await capped.evaluate(()=>JSON.parse(document.querySelector("#afterlife-data").textContent).storage_key);
  assert.equal(await capped.evaluate(key=>localStorage.getItem(key),capKey),null);
  await context.close();assert.deepEqual(errors,[]);assert.deepEqual(network,[]);assert.deepEqual(await fs.readFile(artifact),original);
  console.log("Additive import cancel, shared identity, conflicts, reload and stale-tab preservation passed offline.");
 }finally{await browser.close();await fs.rm(directory,{recursive:true,force:true});}
})().catch(error=>{console.error(error);process.exitCode=1;});
