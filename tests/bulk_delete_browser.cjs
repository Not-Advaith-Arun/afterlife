"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs/promises");
const os = require("node:os");
const path = require("node:path");
const {execFileSync} = require("node:child_process");
const {pathToFileURL} = require("node:url");
const {launch, offlineContext} = require("./browser_support.cjs");

(async () => {
  const directory = await fs.mkdtemp(path.join(os.tmpdir(), "afterlife-bulk-"));
  const root = path.resolve(__dirname, "..");
  const browser = await launch();
  try {
    const records = Array.from({length:205}, (_,index) => ({id:`note-${index}`,title:`Note ${index}`,pages:index,archived:index%2===0}));
    const input = path.join(directory,"records.json"), artifact = path.join(directory,"app.html");
    await fs.writeFile(input,JSON.stringify({records}));
    execFileSync(process.env.PYTHON || "python3",["-m","afterlife","from-python","examples/python-notebook/model.py",input,"-o",artifact],{cwd:root});
    const original = await fs.readFile(artifact);
    const context = await offlineContext(browser,{acceptDownloads:true});
    const errors = [],network = [];
    const open = async () => {
      const page = await context.newPage();
      page.on("pageerror",e => errors.push(e.message));
      page.on("request",r => {if (/^https?:/.test(r.url())) network.push(r.url());});
      await page.goto(pathToFileURL(artifact).href);
      return page;
    };
    const page = await open();
    const key = await page.evaluate(() => JSON.parse(document.querySelector("#afterlife-data").textContent).storage_key);
    const stored = p => p.evaluate(key => localStorage.getItem(key),key);
    await page.locator("#filter-field").selectOption("archived");
    await page.locator("#filter-value").selectOption("true");
    assert.equal(await page.locator("tbody tr").count(),100);
    const before = await stored(page);
    page.once("dialog",dialog => {assert.match(dialog.message(),/103 matching records/); return dialog.dismiss();});
    await page.getByRole("button",{name:"Delete matching records",exact:true}).click();
    assert.equal(await stored(page),before);
    await page.locator('tr[data-record-id="note-0"]').getByRole("button",{name:"Edit",exact:true}).click();
    await page.locator("#field-title").fill("Unfinished draft");
    await page.getByRole("button",{name:"Delete matching records",exact:true}).click();
    await page.locator("#message").filter({hasText:"Save or cancel editor changes"}).waitFor();
    assert.equal(await stored(page),before);
    page.once("dialog",dialog => dialog.accept());
    await page.getByRole("button",{name:"Cancel",exact:true}).click();
    const remove = async () => {
      page.once("dialog",dialog => dialog.accept());
      await page.getByRole("button",{name:"Delete matching records",exact:true}).click();
      await page.locator("#message").filter({hasText:"Deleted 103 matching records"}).waitFor();
    };
    await remove();
    assert.deepEqual(JSON.parse(await stored(page)).records.map(r => r.id),records.filter(r => !r.archived).map(r => r.id));
    await page.getByRole("button",{name:"Undo delete",exact:true}).click();
    await page.locator("#message").filter({hasText:"Deleted records restored."}).waitFor();
    assert.deepEqual(JSON.parse(await stored(page)).records.map(r => r.id),records.map(r => r.id));
    await remove();
    const writer = await open();
    await writer.getByRole("button",{name:"New note",exact:true}).click();
    await writer.locator("#field-title").fill("Independent new record");
    await writer.getByRole("button",{name:"Save record",exact:true}).click();
    await writer.locator("aside.editor").waitFor({state:"hidden"});
    const winning = await stored(writer);
    assert.equal(JSON.parse(winning).records.length,103);
    await page.getByText("Another tab changed this app.",{exact:false}).waitFor();
    await page.getByRole("button",{name:"Undo delete",exact:true}).click();
    assert.equal(await stored(page),winning);
    await page.getByRole("button",{name:"Keep editing a separate copy",exact:true}).click();
    await page.getByRole("button",{name:"Undo delete",exact:true}).click();
    await page.locator("#message").filter({hasText:"Deleted records restored."}).waitFor();
    const download = page.waitForEvent("download");
    await page.getByRole("button",{name:"Export JSON",exact:true}).click();
    const exported = path.join(directory,"separate-copy.json");
    await (await download).saveAs(exported);
    assert.deepEqual(JSON.parse(await fs.readFile(exported,"utf8")).records.map(r => r.id),records.map(r => r.id));
    assert.equal(await stored(writer),winning);
    assert.deepEqual(await fs.readFile(artifact),original);
    assert.deepEqual(errors,[]);assert.deepEqual(network,[]);
    console.log("Bulk deletion: cancel/draft guards, all-page matching, exact undo, stale-tab refusal and separate-copy preservation passed offline.");
    await context.close();
  } finally {await browser.close();await fs.rm(directory,{recursive:true,force:true});}
})().catch(error => {console.error(error);process.exitCode=1;});
