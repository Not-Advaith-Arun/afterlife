/* One Python-to-browser journey spans pagination, persistent reload and tab conflicts. */
"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs/promises");
const os = require("node:os");
const path = require("node:path");
const {execFileSync} = require("node:child_process");
const {pathToFileURL} = require("node:url");
const {launch, offlineContext} = require("./browser_support.cjs");

(async () => {
  const directory = await fs.mkdtemp(path.join(os.tmpdir(), "afterlife-e2e-"));
  const root = path.resolve(__dirname, "..");
  const browser = await launch();
  try {
    const input = path.join(directory, "records.json"), artifact = path.join(directory, "app.html");
    const records = Array.from({length: 205}, (_, index) => ({
      id: `note-${index}`, title: `Note ${index}`, pages: index, archived: index % 2 === 0,
    }));
    await fs.writeFile(input, JSON.stringify({records}));
    execFileSync(process.env.PYTHON || "python3", ["-m", "afterlife", "from-python",
      "examples/python-notebook/model.py", input, "-o", artifact], {cwd: root});
    const context = await offlineContext(browser, {acceptDownloads: true});
    const errors = [], network = [];
    const newPage = async () => {
      const page = await context.newPage();
      page.on("pageerror", error => errors.push(error.message));
      page.on("request", request => { if (/^https?:/.test(request.url())) network.push(request.url()); });
      page.on("dialog", dialog => dialog.accept());
      await page.goto(pathToFileURL(artifact).href);
      return page;
    };
    const first = await newPage();
    assert.equal(await first.locator("tbody tr").count(), 100);
    await first.getByRole("button", {name: "Last page", exact: true}).click();
    assert.equal(await first.locator("tbody tr").count(), 5);
    await first.getByRole("button", {name: "New note", exact: true}).click();
    assert.equal(await first.locator("#field-pages").inputValue(), "0");
    await first.locator("#field-title").fill("Saved note");
    await first.getByRole("button", {name: "Save record", exact: true}).click();
    await first.locator("aside.editor").waitFor({state: "hidden"});
    await first.reload();
    await first.getByRole("button", {name: "Last page", exact: true}).click();
    assert.equal(await first.locator("tbody tr").count(), 6);
    assert.match(await first.locator("tbody").innerText(), /Saved note/);
    const second = await newPage();
    await second.getByRole("button", {name: "New note", exact: true}).click();
    await second.locator("#field-title").fill("Preserved draft");
    await first.getByRole("button", {name: "New note", exact: true}).click();
    await first.locator("#field-title").fill("Winning note");
    await first.getByRole("button", {name: "Save record", exact: true}).click();
    await first.locator("aside.editor").waitFor({state: "hidden"});
    await second.getByText("Another tab changed this app.", {exact: false}).waitFor();
    await second.getByRole("button", {name: "Save record", exact: true}).click();
    assert.equal(await second.locator("#field-title").inputValue(), "Preserved draft");
    const payload = JSON.parse((await fs.readFile(artifact, "utf8"))
      .match(/<script type="application\/json" id="afterlife-data">(.*?)<\/script>/s)[1]);
    let winning = await first.evaluate(key => localStorage.getItem(key), payload.storage_key);
    assert.match(winning, /Winning note/);
    assert.doesNotMatch(winning, /Preserved draft/);
    await second.getByRole("button", {name: "Keep editing a separate copy", exact: true}).click();
    await second.getByRole("button", {name: "Save record", exact: true}).click();
    await second.locator("aside.editor").waitFor({state: "hidden"});
    assert.equal(await first.evaluate(key => localStorage.getItem(key), payload.storage_key), winning);
    const download = second.waitForEvent("download");
    await second.getByRole("button", {name: "Export JSON", exact: true}).click();
    const exported = path.join(directory, "fork.json");
    await (await download).saveAs(exported);
    assert.match(await fs.readFile(exported, "utf8"), /Preserved draft/);
    // A reviewed replacement must not overwrite a newer save in another tab.
    const importing = await newPage();
    const incomingFile = path.join(directory, "import-one.json");
    await fs.writeFile(incomingFile, JSON.stringify({format: "afterlife-data/v1", app_id: payload.spec.app_id,
      spec_fingerprint: payload.spec_fingerprint, records: [payload.records[0]]}));
    await importing.locator("#import-file").setInputFiles(incomingFile);
    await importing.getByRole("heading", {name: "Review import", exact: true}).waitFor();
    await first.getByRole("button", {name: "New note", exact: true}).click();
    await first.locator("#field-title").fill("Concurrent import winner");
    await first.getByRole("button", {name: "Save record", exact: true}).click();
    await first.locator("aside.editor").waitFor({state: "hidden"});
    winning = await first.evaluate(key => localStorage.getItem(key), payload.storage_key);
    assert.match(winning, /Concurrent import winner/);
    await importing.getByText("Another tab changed this app.", {exact: false}).waitFor();
    await importing.getByRole("button", {name: "Apply import", exact: true}).click();
    assert.equal(await first.evaluate(key => localStorage.getItem(key), payload.storage_key), winning);
    assert.equal(await importing.getByRole("heading", {name: "Review import", exact: true}).isVisible(), true);
    const refusedDownload = importing.waitForEvent("download");
    await importing.getByRole("button", {name: "Export JSON", exact: true}).click();
    const refusedFile = path.join(directory, "refused-import.json");
    await (await refusedDownload).saveAs(refusedFile);
    assert.equal(JSON.parse(await fs.readFile(refusedFile, "utf8")).records.length, 207);
    await importing.getByRole("button", {name: "Keep editing a separate copy", exact: true}).click();
    await importing.getByRole("button", {name: "Apply import", exact: true}).click();
    await importing.getByText("Imported 1 records.", {exact: true}).waitFor();
    assert.equal(await importing.locator("tbody tr").count(), 1);
    assert.equal(await first.evaluate(key => localStorage.getItem(key), payload.storage_key), winning);
    // Matching exports must include off-screen pages in the selected view order.
    await first.getByRole("searchbox").fill("Note 1");
    await first.locator("#sort-field").selectOption("pages");
    await first.getByRole("button", {name: "Reverse sort direction", exact: true}).click();
    const expected = payload.records.filter(row => row.title.includes("Note 1")).sort((a, b) => b.pages - a.pages);
    assert.equal(expected.length, 111);
    assert.equal(await first.locator("tbody tr").count(), 100);
    const matchingDownload = first.waitForEvent("download");
    await first.getByRole("button", {name: "Export matching JSON", exact: true}).click();
    const matchingFile = path.join(directory, "matching.json");
    await (await matchingDownload).saveAs(matchingFile);
    const matching = JSON.parse(await fs.readFile(matchingFile, "utf8"));
    assert.deepEqual(matching.records, expected);
    await first.getByRole("button", {name: "Last page", exact: true}).click();
    assert.equal(await first.locator("tbody tr").count(), 11);
    const secondDownload = first.waitForEvent("download");
    await first.getByRole("button", {name: "Export matching JSON", exact: true}).click();
    const secondFile = path.join(directory, "matching-last-page.json");
    await (await secondDownload).saveAs(secondFile);
    assert.deepEqual(JSON.parse(await fs.readFile(secondFile, "utf8")).records, expected);
    assert.equal(await first.evaluate(key => localStorage.getItem(key), payload.storage_key), winning);
    await first.locator("#filter-field").selectOption("archived");
    await first.locator("#filter-value").selectOption("true");
    const filtered = expected.filter(row => row.archived);
    assert.equal(filtered.length, 55);
    assert.equal(await first.locator("tbody tr").count(), filtered.length);
    const csvDownload = first.waitForEvent("download");
    await first.getByRole("button", {name: "Export matching CSV", exact: true}).click();
    const csvFile = path.join(directory, "filtered.csv");
    await (await csvDownload).saveAs(csvFile);
    const table = JSON.parse(execFileSync(process.env.PYTHON || "python3", ["-c",
      "import csv,io,json,sys; print(json.dumps(list(csv.reader(io.StringIO(sys.stdin.read())))))"],
      {input: await fs.readFile(csvFile, "utf8"), encoding: "utf8"}));
    const columns = table[0];
    assert.deepEqual(columns, ["id", ...payload.spec.fields.map(field => field.name)]);
    assert.equal(table.length, filtered.length + 1);
    assert.deepEqual(table.slice(1).map(row => row[0]), filtered.map(row => "'" + row.id));
    assert.deepEqual(table.slice(1).map(row => row[columns.indexOf("pages")]), filtered.map(row => String(row.pages)));
    assert.ok(table.slice(1).every(row => row[columns.indexOf("archived")] === "true"));
    assert.ok(table.slice(1).every(row => row[columns.indexOf("body")] === "'First line\nSecond line"));
    assert.ok(table.slice(1).every(row => row[columns.indexOf("rating")] === ""));
    await first.getByRole("button", {name: "Reset view", exact: true}).click();
    assert.equal(await first.getByRole("searchbox").inputValue(), "");
    assert.equal(await first.locator("#sort-field").inputValue(), "");
    assert.equal(await first.locator("#filter-field").inputValue(), "");
    assert.equal(await first.locator("#filter-value").isDisabled(), true);
    assert.equal(await first.getByRole("button", {name: "Reverse sort direction", exact: true}).isDisabled(), true);
    assert.equal(await first.locator("tbody tr").count(), 100);
    assert.equal(await first.evaluate(key => localStorage.getItem(key), payload.storage_key), winning);
    const completeDownload = first.waitForEvent("download");
    await first.getByRole("button", {name: "Export JSON", exact: true}).click();
    const completeFile = path.join(directory, "complete.json");
    await (await completeDownload).saveAs(completeFile);
    assert.equal(JSON.parse(await fs.readFile(completeFile, "utf8")).records.length, 208);
    await first.reload();
    assert.equal(await first.evaluate(key => localStorage.getItem(key), payload.storage_key), winning);
    // Undo retains an old collection too: it must never replace a newer tab's saved records.
    const deleting = await newPage();
    await deleting.getByRole("searchbox").fill("Note 0");
    assert.equal(await deleting.locator("tbody tr").count(), 1);
    await deleting.getByRole("button", {name: "Delete", exact: true}).click();
    await deleting.getByText("Record deleted. Undo is available until the next import or reload.", {exact: true}).waitFor();
    const writing = await newPage();
    await writing.getByRole("button", {name: "New note", exact: true}).click();
    await writing.locator("#field-title").fill("Newer save after deletion");
    await writing.getByRole("button", {name: "Save record", exact: true}).click();
    await writing.locator("aside.editor").waitFor({state: "hidden"});
    const newer = await writing.evaluate(key => localStorage.getItem(key), payload.storage_key);
    assert.match(newer, /Newer save after deletion/);
    assert.equal(JSON.parse(newer).records.some(record => record.id === "note-0"), false);
    await deleting.getByText("Another tab changed this app.", {exact: false}).waitFor();
    await deleting.getByRole("button", {name: "Undo delete", exact: true}).click();
    assert.equal(await writing.evaluate(key => localStorage.getItem(key), payload.storage_key), newer);
    assert.equal(await deleting.locator("tbody tr").count(), 0);
    await deleting.getByRole("button", {name: "Keep editing a separate copy", exact: true}).click();
    await deleting.getByRole("button", {name: "Undo delete", exact: true}).click();
    await deleting.getByText("Deleted record restored.", {exact: true}).waitFor();
    assert.equal(await deleting.locator("tbody tr").count(), 1);
    assert.equal(await deleting.getByRole("button", {name: "Undo delete", exact: true}).isVisible(), false);
    const undoDownload = deleting.waitForEvent("download");
    await deleting.getByRole("button", {name: "Export JSON", exact: true}).click();
    const undoFile = path.join(directory, "undo-separate-copy.json");
    await (await undoDownload).saveAs(undoFile);
    const undone = JSON.parse(await fs.readFile(undoFile, "utf8")).records;
    assert.equal(undone.length, 208);
    assert.equal(undone.some(record => record.id === "note-0"), true);
    assert.equal(undone.some(record => record.title === "Newer save after deletion"), false);
    assert.equal(await writing.evaluate(key => localStorage.getItem(key), payload.storage_key), newer);
    await writing.reload();
    assert.equal(await writing.evaluate(key => localStorage.getItem(key), payload.storage_key), newer);
    assert.deepEqual(errors, []);
    assert.deepEqual(network, []);
    // A duplicate is a draft until Save, with a fresh ID and exact typed values.
    const duplicateContext = await offlineContext(browser, {acceptDownloads: true});
    const duplicatePage = await duplicateContext.newPage();
    duplicatePage.on("pageerror", error => errors.push(error.message));
    duplicatePage.on("request", request => { if (/^https?:/.test(request.url())) network.push(request.url()); });
    duplicatePage.on("dialog", dialog => dialog.accept());
    await duplicatePage.goto(pathToFileURL(artifact).href);
    const originalRecord = payload.records[0];
    await duplicatePage.locator('tr[data-record-id="note-0"]').getByRole("button", {name: "Duplicate", exact: true}).click();
    assert.equal(await duplicatePage.locator("#field-title").inputValue(), originalRecord.title);
    assert.equal(await duplicatePage.locator("#field-pages").inputValue(), String(originalRecord.pages));
    assert.equal(await duplicatePage.locator("#field-archived").isChecked(), originalRecord.archived);
    assert.equal(await duplicatePage.locator("#field-body").inputValue(), originalRecord.body);
    await duplicatePage.getByRole("button", {name: "Cancel", exact: true}).click();
    assert.equal(await duplicatePage.evaluate(key => localStorage.getItem(key), payload.storage_key), null);
    await duplicatePage.locator('tr[data-record-id="note-0"]').getByRole("button", {name: "Duplicate", exact: true}).click();
    await duplicatePage.locator("#field-title").fill("Duplicated note");
    await duplicatePage.getByRole("button", {name: "Save record", exact: true}).click();
    await duplicatePage.locator("aside.editor").waitFor({state: "hidden"});
    const duplicated = JSON.parse(await duplicatePage.evaluate(key => localStorage.getItem(key), payload.storage_key)).records;
    assert.equal(duplicated.length, 206);
    assert.deepEqual(duplicated.find(record => record.id === "note-0"), originalRecord);
    const copy = duplicated.find(record => record.title === "Duplicated note");
    assert.notEqual(copy.id, originalRecord.id);
    assert.deepEqual({...copy, id: originalRecord.id, title: originalRecord.title}, originalRecord);
    await duplicatePage.reload();
    await duplicatePage.getByRole("searchbox").fill("Duplicated note");
    assert.equal(await duplicatePage.locator("tbody tr").count(), 1);
    assert.deepEqual(errors, []);
    assert.deepEqual(network, []);
    await duplicateContext.close();
    await context.close();
    console.log("PASS Python conversion, page bounds, persistent reload, editor/import conflict-copy recovery and complete ordered matching exports across pages");
  } finally {
    await browser.close();
    await fs.rm(directory, {recursive: true, force: true});
  }
})().catch(error => {console.error(error); process.exitCode = 1;});
